# frozen_string_literal: true

module Edgeway
  module CLI
    class Test
      PLATFORMS = []

      def self.run(args)
        root = Dir.pwd
        database = Build::DatabaseConfig.new(root)
        (PLATFORMS.find { |platform| platform.handles?(database) } || Test).new(root).run(args)
      end

      def initialize(root)
        @root = root
      end

      def run(args)
        Precheck.sqlite!
        write_test_app
        exec("spinel_test-unit", "-I", @root, "-I", CLI.gem_dir + "/lib", *args)
      end

      def write_test_app
        raise Error, "no config/routes.rb in #{@root}" unless File.exist?(File.join(@root, "config/routes.rb"))

        FileUtils.mkdir_p(File.join(@root, "tmp"))
        lines = ["# Generated by `edgeway test` from app/ and config/; do not edit.", 'require "edgeway"']
        lines.concat(database_lines)
        lines << ""
        views = Build::ViewCompiler.new(@root).compile
        File.write(File.join(@root, "tmp/views.rb"), views) if views
        lines.concat(Build::AppFiles.new(@root).require_lines(views: views && "views"))
        File.write(File.join(@root, "tmp/test_app.rb"), lines.join("\n") + "\n")
      end

      private

      def database_lines
        [
          'require "edgeway/db/memory"',
          'require "edgeway/db/sqlite"',
          'require "edgeway/test/sqlite_databases"',
          # Where the migrations are read from at test time (the binary may run
          # from another directory); Edgeway::TestDatabases applies them.
          "module Edgeway; TEST_APP_ROOT = #{@root.dump}; end",
          "module Edgeway; TEST_DATABASES = #{Build::DatabaseConfig.new(@root).names.inspect}; end"
        ]
      end
    end
  end
end
