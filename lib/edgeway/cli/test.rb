# frozen_string_literal: true

module Edgeway
  module CLI
    class Test
      def self.run(args)
        root = Dir.pwd
        Precheck.sqlite!
        new(root).write_test_app
        exec("spinel_test-unit", "-I", root, "-I", CLI.gem_dir + "/lib", *args)
      end

      def initialize(root)
        @root = root
      end

      def write_test_app
        raise Error, "no config/routes.rb in #{@root}" unless File.exist?(File.join(@root, "config/routes.rb"))

        FileUtils.mkdir_p(File.join(@root, "tmp"))
        lines = ["# Generated by `edgeway test` from app/ and config/; do not edit.", 'require "edgeway"']
        lines << 'require "edgeway/db/memory"'
        lines << 'require "edgeway/db/sqlite"'
        # Where the migrations are read from at test time (the binary may run
        # from another directory); Edgeway::UnitTest#setup applies them.
        lines << "module Edgeway; TEST_APP_ROOT = #{@root.dump}; end"
        lines << ""
        views = Build::ViewCompiler.new(@root).compile
        File.write(File.join(@root, "tmp/views.rb"), views) if views
        lines.concat(Build::AppFiles.new(@root).require_lines(views: views && "views"))
        File.write(File.join(@root, "tmp/test_app.rb"), lines.join("\n") + "\n")
      end
    end
  end
end
