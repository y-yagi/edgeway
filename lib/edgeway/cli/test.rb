# frozen_string_literal: true

module Edgeway
  module CLI
    # edgeway test [ARGS]: writes tmp/test_app.rb (build/ is `edgeway build`'s), the app's requires in
    # Build's order (Spinel resolves require at compile time, so edgeway/test
    # cannot glob app/ itself), then runs spinel_test-unit with ARGS and the app root and the gem's lib/ as -I
    # (so `require "tmp/test_app"` resolves). It rewrites the file on every run;
    # this is the only supported way to run the tests. Before that, Precheck
    # verifies -lsqlite3 links.
    class Test
      def self.run(args)
        root = Dir.pwd
        Precheck.sqlite!
        new(root).write_test_app
        exec("spinel_test-unit", "-I", root, "-I", CLI.gem_dir + "/lib", *args)
      end

      def initialize(root)
        @root = root
      end

      def write_test_app
        raise Error, "no config/routes.rb in #{@root}" unless File.exist?(File.join(@root, "config/routes.rb"))

        FileUtils.mkdir_p(File.join(@root, "tmp"))
        lines = ["# Generated by `edgeway test` from app/ and config/; do not edit.", 'require "edgeway"']
        lines << 'require "edgeway/db/memory"'
        lines << 'require "edgeway/db/sqlite"'
        # Where the migrations are read from at test time (the binary may run
        # from another directory); Edgeway::IntegrationTest#setup applies them.
        lines << "module Edgeway; TEST_APP_ROOT = #{@root.dump}; end"
        lines << ""
        lines.concat(AppFiles.new(@root).require_lines)
        File.write(File.join(@root, "tmp/test_app.rb"), lines.join("\n") + "\n")
      end
    end
  end
end
