# frozen_string_literal: true

require "json"
require "open3"
require "tempfile"
require "rbconfig"
require_relative "class_source"

module Edgeway
  module CLI
    class Build
      class DispatchCompiler
        PROBE = File.join(__dir__, "dispatch_probe.rb")

        def initialize(root, library_lines)
          @root = root
          @library_lines = library_lines
        end

        def compile
          controllers = routed_actions
          return nil if controllers.empty?

          lines = ["# Generated by `edgeway build` from config/routes.rb; do not edit."]
          controllers.each { |name, actions| lines.concat(ClassSource.wrap(name, run_action_source(actions))) }
          lines.concat(instantiate_source(controllers.keys))
          lines.join("\n") + "\n"
        end

        private

        def routed_actions
          result = probe
          problems = result["problems"]
          raise Error, "config/routes.rb:\n  #{problems.join("\n  ")}" if problems

          result.fetch("controllers")
        end

        def probe
          Tempfile.create("dispatch") do |result|
            _output, error, status = Open3.capture3(*probe_command(result.path))
            raise Error, "could not load the app to read its routes:\n#{error}" unless status.success?

            JSON.parse(File.read(result.path))
          end
        rescue JSON::ParserError => parse_error
          raise Error, "could not read the routes of the app (#{parse_error.message})"
        end

        def probe_command(result_path)
          [RbConfig.ruby, "-I", File.join(CLI.gem_dir, "lib"), PROBE, result_path, @root,
           @library_lines.join("\n"), *AppFiles.new(@root).files]
        end

        def run_action_source(actions)
          lines = ["def _run_action(action)", "  case action"]
          actions.each { |action| lines << "  when #{action.dump} then self.#{action}" }
          lines << "  end" << "end"
        end

        def instantiate_source(names)
          lines = ["", "module Edgeway", "  module Controller", "    module Dispatcher",
                   "      def self.instantiate(name, request)", "        case name"]
          names.each { |name| lines << "        when #{name.dump} then #{name}.new(request)" }
          lines << "        end" << "      end" << "    end" << "  end" << "end"
        end
      end
    end
  end
end
