# frozen_string_literal: true

require_relative "../../inflector"

module Edgeway
  module CLI
    class Build
      # app/views/**/*.html.erb -> Ruby that reopens the controllers.
      #
      # Spinel has no eval and no binding, so a template can't be read at
      # runtime: each one becomes an instance method of its controller (it sees
      # the action's @variables, params and helpers as any method of it does),
      # and `edgeway build` / `edgeway test` require the result after the
      # controllers.
      #
      #   app/views/todos/index.html.erb   TodosController#_view_todos_index
      #   app/views/layouts/application.html.erb
      #                                    ApplicationController#_render_layout
      #
      # A controller gets `_render_view(action)` too: a case over its templates,
      # not a send, since with a computed name Spinel's send misses the methods
      # of a subclass (matz/spinel#8592).
      #
      # The ERB it reads is a small subset (stdlib ERB is not used):
      #   <%= expr %>    expr, HTML-escaped
      #   <%== expr %>   expr, as it is
      #   <% code %>     code
      #   <%# text %>    nothing
      #   <%%            a literal <%
      #   <%-            starts a tag and drops the indentation before it
      #   -%>            ends a tag and drops the newline after it
      # and `<%= yield %>` (or `<%== yield %>`) in the layout is the page, as
      # it is.
      class ViewCompiler
        EXT = ".html.erb"
        LAYOUT = "layouts/application#{EXT}"
        NAME = /\A[a-z_][a-z0-9_]*\z/

        def initialize(root)
          @root = root
        end

        # The Ruby for app/views, nil when the app has none.
        def compile
          views = File.join(@root, "app/views")
          return nil unless Dir.exist?(views)

          files = Dir.glob("**/*#{EXT}", base: views).sort
          layout = files.delete(LAYOUT)
          files.reject! { |f| f.start_with?("layouts/") }
          by_dir = {}
          files.each do |f|
            dir = File.dirname(f)
            raise Error, "app/views/#{f}: a template goes in a controller's directory (app/views/todos/index#{EXT})" if dir == "."

            (by_dir[dir] ||= []) << f
          end

          out = ["# Generated by `edgeway build` from app/views; do not edit."]
          out.concat(layout_source(layout)) if layout
          by_dir.each { |dir, fs| out.concat(controller_source(dir, fs)) }
          out.join("\n") + "\n"
        end

        def template_lines(text, path, layout: false)
          lines = []
          pos = 0
          literal = +""
          # the line of text[counted], advanced as the scan goes
          counted = 0
          line = 1
          while (open = text.index("<%", pos))
            if text[open + 2] == "%"
              literal << text[pos...open] << "<%"
              pos = open + 3
              next
            end
            line += text[counted...open].count("\n")
            counted = open
            close = text.index("%>", open + 2) or raise Error, "#{path}:#{line}: unclosed <%"
            literal << text[pos...open]
            body = text[(open + 2)...close]
            if body.start_with?("-")
              body = body[1..]
              # <%- also drops the indentation before it on its line
              line_start = open > 0 ? (text.rindex("\n", open - 1) || -1) + 1 : 0
              indent = open - line_start
              literal = literal[0...(literal.length - indent)] if indent > 0 && text[line_start...open].strip.empty?
            end
            trim = body.end_with?("-")
            body = body.chomp("-") if trim
            after = close + 2
            if trim && text[after] == "\n"
              after += 1
            elsif trim && text[after, 2] == "\r\n"
              after += 2
            end
            flush(lines, literal)
            code = body.strip
            if body.start_with?("#")
            elsif body.start_with?("==")
              expr = code[2..].strip
              lines << "# #{path}:#{line}" << output(expr, "(", ").to_s", layout, path, line)
            elsif body.start_with?("=")
              expr = code[1..].strip
              lines << "# #{path}:#{line}" << output(expr, "Edgeway::View.escape(", ")", layout, path, line)
            else
              lines << "# #{path}:#{line}" << code
            end
            pos = after
          end
          literal << text[pos..]
          flush(lines, literal)
          lines
        end

        private

        # An output tag; the closing paren goes on its own line so that a
        # trailing `# comment` in the tag doesn't swallow it. `yield` is the
        # page in the layout.
        def output(expr, head, tail, layout, path, line)
          if expr == "yield"
            raise Error, "#{path}:#{line}: yield is only for the layout" unless layout

            return "out << content"
          end
          "out << #{head}#{expr}\n#{tail}"
        end

        def flush(lines, literal)
          return if literal.empty?

          lines << "out << #{literal.dump}"
          literal.clear
        end

        def layout_source(file)
          path = "app/views/#{file}"
          controller_file!("application", path)
          body = template_lines(File.read(File.join(@root, path)), path, layout: true)
          wrap("ApplicationController", method_source("_render_layout(content)", body, path))
        end

        def controller_source(dir, files)
          controller_file!(dir, "app/views/#{dir}/")
          methods = []
          actions = []
          files.each do |f|
            path = "app/views/#{f}"
            action = File.basename(f).delete_suffix(EXT)
            raise Error, "#{path}: #{action.inspect} is not a valid action name" unless NAME.match?(action)
            dir.split("/").each { |part| raise Error, "#{path}: #{part.inspect} is not a valid controller path" unless NAME.match?(part) }

            name = "_view_#{dir.tr("/", "_")}_#{action}"
            methods.concat(method_source(name, template_lines(File.read(File.join(@root, path)), path), path))
            methods << ""
            actions << [action, name]
          end
          dispatch = ["def _render_view(action)", "  case action"]
          actions.each { |action, name| dispatch << "  when #{action.dump} then #{name}" }
          dispatch << "  else super" << "  end" << "end"
          wrap(Inflector.controller_class_name(dir), methods + dispatch)
        end

        def method_source(signature, body, path)
          ["def #{signature}", "  # #{path}", "  out = +\"\""] +
            body.map { |l| "  #{l}" } + ["  out", "end"]
        end

        def wrap(klass, body)
          *modules, name = klass.split("::")
          depth = modules.size
          lines = [""]
          modules.each_with_index { |m, i| lines << "#{"  " * i}module #{m}" }
          lines << "#{"  " * depth}class #{name}"
          body.each { |l| lines << (l.empty? ? "" : "#{"  " * (depth + 1)}#{l}") }
          lines << "#{"  " * depth}end"
          modules.size.times { |i| lines << "#{"  " * (modules.size - 1 - i)}end" }
          lines
        end

        def controller_file!(dir, what)
          return if File.exist?(File.join(@root, "app/controllers/#{dir}_controller.rb"))

          raise Error, "#{what} has no controller: app/controllers/#{dir}_controller.rb does not exist"
        end
      end
    end
  end
end
