# frozen_string_literal: true

require "optparse"
require "json"
require_relative "build/app_config"
require_relative "build/app_files"
require_relative "build/cache_config"
require_relative "build/dispatch_compiler"
require_relative "build/js_files"
require_relative "build/platform_config"
require_relative "build/view_compiler"

module Edgeway
  module CLI
    # edgeway build: app/, config/ -> build/main.rb -> build/app.wasm, and the
    # gem's js/ -> build/edgeway/. Spinel compiles with --incremental (cached C
    # units, fast rebuilds, no inlining across units) unless --release, which
    # builds as one unit for deploying and strips the DWARF debug info from
    # build/app.wasm.
    #
    # Spinel resolves require at compile time and has no autoloading, so
    # build/main.rb requires every file, in an order where a class body finds
    # what it names (a superclass, an extended module):
    #   1. edgeway, the database adapter config/database.yml names, the services
    #      of the platform config/edgeway.yml names (see PlatformConfig), and
    #      the cache store config/cache.yml names (when it needs a file)
    #   2. app/*/ other than models/ and controllers/ (services, ...)
    #   3. app/models/
    #   4. app/controllers/
    #   5. build/views.rb, the Ruby compiled from app/views (when there is one)
    #   6. build/dispatch.rb, the Ruby generated from the routes (see DispatchCompiler)
    #   7. config/routes.rb
    # Within each, application_*.rb come first (the base classes), then the
    # rest by path (byte order).
    class Build
      def self.run(args)
        env = "development"
        release = false
        OptionParser.new do |o|
          o.banner = "Usage: edgeway build [--env ENV] [--release]"
          o.on("--env ENV", "environment (default: development)") { |v| env = v }
          o.on("--release", "build as one unit, without --incremental, and strip debug info (for deploying)") { release = true }
        end.parse!(args)
        new(Dir.pwd, env, release:).run
      end

      def initialize(root, env, release: false, platform: nil)
        @root = root
        @env = env
        @release = release
        @platform = platform
      end

      def run
        raise Error, "no config/routes.rb in #{@root}" unless File.exist?(File.join(@root, "config/routes.rb"))

        config = AppConfig.load(@root, @env)
        FileUtils.mkdir_p(File.join(@root, "build"))
        write_main(config)
        copy_js(config)
        compile
        puts "built build/app.wasm (#{@env})"
      end

      private

      def write_main(config)
        cache = CacheConfig.load(@root, @env)
        check_platform_supports(config, cache)
        library = library_lines(config, cache)
        lines = ["# Generated by `edgeway build` from app/ and config/; do not edit.", *library, ""]
        lines << connection_line(config)
        config.databases.each { |name, binding_name| lines << connect_line(config, name, binding_name) }
        lines.concat(platform.setup_lines)
        lines << "Edgeway.cache = #{cache.store_expression}"
        lines.concat(platform.rate_limiter_lines)
        lines << ""
        lines.concat(app_lines(library))
        lines << ""
        lines << "Edgeway::Server.run"
        File.write(File.join(@root, "build/main.rb"), lines.join("\n") + "\n")
      end

      def library_lines(config, cache)
        lines = ['require "edgeway"', "require #{config.adapter_file.dump}", *platform.service_lines]
        lines << "require #{cache.backend_file.dump}" if cache.backend_file
        lines
      end

      def app_lines(library)
        views = ViewCompiler.new(@root).compile
        File.write(File.join(@root, "build/views.rb"), views) if views
        dispatch = DispatchCompiler.new(@root, library).compile
        File.write(File.join(@root, "build/dispatch.rb"), dispatch) if dispatch
        AppFiles.new(@root).require_lines(views: views && "views", dispatch: dispatch && "dispatch")
      end

      def platform
        @platform ||= PlatformConfig.load(@root)
      end

      def check_platform_supports(config, cache)
        unsupported("database adapter", config.adapter) unless platform.adapters.include?(config.adapter)
        unsupported("cache store", cache.store) unless platform.stores.include?(cache.store)
      end

      def unsupported(kind, value)
        raise Error, "#{kind} #{value.inspect} is not supported on platform #{platform.name.inspect}"
      end

      def connection_line(config)
        "Edgeway::Model.connection = #{adapter_expression(config, config.binding_name)}"
      end

      def connect_line(config, name, binding_name)
        "Edgeway::Model.connect(#{name.inspect}, #{adapter_expression(config, binding_name)})"
      end

      def adapter_expression(config, binding_name)
        platform.adapter_expression(config.adapter, binding_name)
      end

      def copy_js(config)
        JsFiles.copy(File.join(@root, "build/edgeway"), config_js(config), platform.js_paths)
      end

      def config_js(config)
        values = { "env" => config.env, "d1Binding" => config.binding_name, "sessions" => config.sessions }
        JsFiles.config_js(values, "build")
      end

      def compile
        spinel = Toolchain.spinel || raise(Error, "no Spinel compiler found (install it with mise, or set SPINEL=/path/to/spinel)")
        cmd = [spinel, "-I", File.join(CLI.gem_dir, "lib"), "--target=wasm32-wasi", "build/main.rb", "-o", "build/app.wasm"]
        cmd << "--incremental" unless @release
        puts cmd.join(" ")
        system(*cmd, chdir: @root) || raise(Error, "spinel failed")
        strip_debug_info if @release
      end

      def strip_debug_info
        strip = strip_tool
        unless strip
          warn("edgeway: warning: no llvm-strip in the WASI SDK; build/app.wasm keeps its debug info")
          return
        end

        # --strip-debug and not --strip-all: the name section stays, so stack traces keep their function names.
        command = [strip, "--strip-debug", "build/app.wasm"]
        puts command.join(" ")
        system(*command, chdir: @root) || raise(Error, "llvm-strip failed")
      end

      def strip_tool
        sdk = Toolchain.wasi_sdk
        tool = sdk && File.join(sdk, "bin/llvm-strip")
        tool if tool && File.executable?(tool)
      end
    end
  end
end
