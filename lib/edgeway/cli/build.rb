# frozen_string_literal: true

require "optparse"
require "json"

module Edgeway
  module CLI
    # edgeway build: app/, config/ -> build/main.rb -> build/app.wasm, and the
    # gem's js/ -> build/edgeway/.
    #
    # Spinel resolves require at compile time and has no autoloading, so
    # build/main.rb requires every file, in an order where a class body finds
    # what it names (a superclass, an extended module):
    #   1. edgeway, the database adapter config/database.yml names, and the JWT
    #      verifier
    #   2. app/*/ other than models/ and controllers/ (services, ...)
    #   3. app/models/
    #   4. app/controllers/
    #   5. config/routes.rb
    # Within each, application_*.rb come first (the base classes), then the
    # rest by path (byte order).
    class Build
      def self.run(args)
        env = "development"
        OptionParser.new do |o|
          o.banner = "Usage: edgeway build [--env ENV]"
          o.on("--env ENV", "environment (default: development)") { |v| env = v }
        end.parse!(args)
        new(Dir.pwd, env).run
      end

      def initialize(root, env)
        @root = root
        @env = env
      end

      def run
        raise Error, "no config/routes.rb in #{@root}" unless File.exist?(File.join(@root, "config/routes.rb"))

        config = AppConfig.load(@root, @env)
        FileUtils.mkdir_p(File.join(@root, "build"))
        write_main(config)
        copy_js(config)
        compile
        puts "built build/app.wasm (#{@env})"
      end

      private

      def write_main(config)
        lines = ["# Generated by `edgeway build` from app/ and config/; do not edit.", 'require "edgeway"']
        lines << "require #{config.adapter_file.dump}"
        # Always: js/cloudflare.js supplies the edgeway_jwt import to every app,
        # and the verifier is only called by an app that authenticates.
        lines << 'require "edgeway/service/cloudflare/jwt"'
        lines << ""
        lines << connection_line(config)
        lines << "Edgeway::Auth.verifier = Edgeway::Cloudflare::JWTVerifier.new"
        lines << ""
        lines.concat(AppFiles.new(@root).require_lines)
        lines << ""
        lines << "Edgeway::Server.run"
        File.write(File.join(@root, "build/main.rb"), lines.join("\n") + "\n")
      end

      def connection_line(config)
        case config.adapter
        when "d1" then %(Edgeway::Model.connection = Edgeway::Cloudflare::D1Adapter.new(binding: #{config.binding_name.inspect}))
        else "Edgeway::Model.connection = Edgeway::DB::MemoryAdapter.new"
        end
      end

      def copy_js(config)
        dest = File.join(@root, "build/edgeway")
        FileUtils.mkdir_p(dest)
        Dir.glob(File.join(CLI.gem_dir, "js/*.js")).each { |f| FileUtils.cp(f, dest) }
        js = "// Generated by `edgeway build` from config/database.yml; do not edit.\n" \
             "export default #{JSON.generate({ "env" => config.env, "d1Binding" => config.binding_name })};\n"
        File.write(File.join(dest, "config.js"), js)
      end

      def compile
        spinel = Toolchain.spinel || raise(Error, "no Spinel compiler found (install it with mise, or set SPINEL=/path/to/spinel)")
        cmd = [spinel, "-I", File.join(CLI.gem_dir, "lib"), "--target=wasm32-wasi", "build/main.rb", "-o", "build/app.wasm"]
        puts cmd.join(" ")
        system(*cmd, chdir: @root) || raise(Error, "spinel failed")
      end
    end
  end
end
